export function parseTraineeNameField(rawName: string): {
  courseAbbreviation: string;
  rollOrCode: string;
  traineeName: string;
  guardianName: string;
} {
  const parts = rawName.split('-').map((p) => p.trim());
  let courseAbbr = 'OTHER';
  let rollCode = parts[0] || '';
  let tName = parts[1] || '';
  let gName = parts.slice(2).join(' - ') || '';

  const upper = rollCode.toUpperCase();
  if (upper.startsWith('MVII') || upper.startsWith('MV2')) {
    courseAbbr = 'MVii';
  } else if (upper.startsWith('MVI') || upper.startsWith('MV1')) {
    courseAbbr = 'MVi';
  } else if (upper.startsWith('ADDM')) {
    courseAbbr = 'ADDM';
  } else if (upper.startsWith('BTE')) {
    courseAbbr = 'BTE';
  } else if (upper.startsWith('BT')) {
    courseAbbr = 'BT';
  } else if (upper.startsWith('CK')) {
    courseAbbr = 'CK';
  } else if (upper.startsWith('CO')) {
    courseAbbr = 'CO';
  } else if (upper.startsWith('DM')) {
    courseAbbr = 'DM';
  } else if (upper.startsWith('FD')) {
    courseAbbr = 'FD';
  } else if (upper.startsWith('TUV')) {
    courseAbbr = 'TUV';
  }

  // Check D/O notation in name or parts
  if (tName.includes(' D/O ') || tName.includes(' d/o ')) {
    const sub = tName.split(/ D\/O | d\/o /i);
    tName = sub[0].trim();
    if (!gName) gName = sub[1]?.trim() || '';
  }

  return {
    courseAbbreviation: courseAbbr,
    rollOrCode: rollCode,
    traineeName: tName || rawName,
    guardianName: gName || '—',
  };
}

